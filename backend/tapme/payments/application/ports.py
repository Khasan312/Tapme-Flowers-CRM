from decimal import Decimal
from typing import Protocol
from uuid import UUID

from tapme.payments.domain import Payment


class PaymentRepository(Protocol):
    def balance(self, business_id: UUID, order_id: UUID) -> Decimal: ...
    def by_request(self, business_id: UUID, key: UUID) -> Payment | None: ...
    def add(self, payment: Payment) -> None: ...
    def list(self, business_id: UUID, order_id: UUID) -> tuple[Payment, ...]: ...
