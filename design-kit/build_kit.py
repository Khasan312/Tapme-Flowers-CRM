# -*- coding: utf-8 -*-
"""Build the readable HTML design kit from the three mockup generators.

Runs design-reminders/v2/build_v2.py, design-crm/build_crm.py and
design-onboarding/build_onb.py (each also refreshes its own HTML), then writes:

  design-kit/css/base.css        tokens, rail, topbar, buttons, tags (design-reminders/build.py)
  design-kit/css/components.css  shared screen components (design-reminders/v2)
  design-kit/css/crm.css         chats, clients, client card (design-crm)
  design-kit/css/onboarding.css  setup checklist, channels, points (design-onboarding)
  design-kit/screens/*.html      every screen, linking only the CSS it was built with

Run from the repository root:
  python3 design-kit/build_kit.py
  frontend/node_modules/.bin/prettier --write "design-kit/screens/*.html" "design-kit/css/*.css"
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT = os.path.join(ROOT, "design-kit")


def run(rel):
    path = os.path.join(ROOT, rel)
    ns = {"__file__": path, "__name__": "kit"}
    cwd = os.getcwd()
    try:
        os.chdir(os.path.dirname(path))
        exec(compile(open(path, encoding="utf-8").read(), path, "exec"), ns)
    finally:
        os.chdir(cwd)
    return ns


v2 = run("design-reminders/v2/build_v2.py")
crm = run("design-crm/build_crm.py")
onb = run("design-onboarding/build_onb.py")

# Order matters: every page's <style> is base + components (+ crm) (+ onboarding) (+ local).
PIECES = [
    ("base.css", v2["CSS"]),
    ("components.css", v2["EXTRA"]),
    ("crm.css", crm["CSS"]),
    ("onboarding.css", onb["CSS"]),
]

SCREENS = [
    ("reminders-1-list", v2["OUT"]["1-list.html"]),
    ("reminders-2-queue-card", v2["OUT"]["2-queue-card.html"]),
    ("reminders-3-week-board", v2["OUT"]["3-week-board.html"]),
    ("reminders-4-settings-scenarios", v2["OUT"]["4-settings-scenarios.html"]),
    ("reminders-5-mobile", v2["OUT"]["5-mobile.html"]),
    ("crm-1-chats", crm["OUT"]["1-chats.html"]),
    ("crm-2-clients", crm["OUT"]["2-clients.html"]),
    ("crm-3-client-card", crm["OUT"]["3-client-card.html"]),
    ("crm-4-mobile", crm["OUT"]["4-mobile.html"]),
    ("onboarding-1-setup", onb["OUT"]["1-setup.html"]),
    ("onboarding-2-channels", onb["OUT"]["2-channels.html"]),
    ("onboarding-3-points", onb["OUT"]["3-points.html"]),
    ("onboarding-4-first-login", onb["OUT"]["4-first-login.html"]),
]

HEADER = "/* Generated by design-kit/build_kit.py from {src}. Edit the generator, not this file. */\n"
SOURCES = {
    "base.css": "design-reminders/build.py",
    "components.css": "design-reminders/v2/build_v2.py",
    "crm.css": "design-crm/build_crm.py",
    "onboarding.css": "design-onboarding/build_onb.py",
}


def split_style(style):
    """Return (css files used, page-local css) for one page's <style> body."""
    used, rest = [], style
    for name, css in PIECES:
        if rest.startswith(css):
            used.append(name)
            rest = rest[len(css):]
    return used, rest.strip()


def main():
    os.makedirs(os.path.join(KIT, "css"), exist_ok=True)
    os.makedirs(os.path.join(KIT, "screens"), exist_ok=True)
    for name, css in PIECES:
        with open(os.path.join(KIT, "css", name), "w", encoding="utf-8") as f:
            f.write(HEADER.format(src=SOURCES[name]) + css.strip() + "\n")
    for name, html in SCREENS:
        m = re.search(r"<style>(.*?)</style>", html, flags=re.S)
        if not m:
            raise SystemExit("no <style> in " + name)
        used, local = split_style(m.group(1))
        if not used:
            raise SystemExit("unexpected CSS order in " + name)
        links = "".join('<link rel="stylesheet" href="../css/%s">' % u for u in used)
        if local:
            links += "<style>/* Only for this screen */\n" + local + "</style>"
        out = html[: m.start()] + links + html[m.end():]
        out = out.replace("<!doctype html><html", "<!doctype html>\n<html", 1)
        out = out.replace(
            '<meta charset="utf-8">',
            '<meta charset="utf-8"><meta name="viewport" content="width=1440">'
            "<!-- Mockup at a fixed 1440x900 canvas. Generated by design-kit/build_kit.py -->",
            1,
        )
        with open(os.path.join(KIT, "screens", name + ".html"), "w", encoding="utf-8") as f:
            f.write(out)
        print("screen", name, "->", ", ".join(used) + (" + local" if local else ""))


main()
